import type { AudioMetrics, MixReport, SoundscapeBlueprint } from '@/types';

function bullet(items: string[]): string {
  return items.length > 0 ? items.map((item) => `- ${item}`).join('\n') : '- None reported';
}

export function blueprintToMarkdown(
  blueprint: SoundscapeBlueprint,
  meta: { model: string | null; generatedAt: string },
): string {
  const sections = blueprint.arrangement
    .map(
      (section) =>
        `### ${section.name}\n\n- Energy: ${Math.round(section.energy * 100)}%\n- Bars: ${
          section.bars ?? 'not specified'
        }\n- Elements: ${section.elements.join(', ') || 'none listed'}\n- Notes: ${
          section.notes ?? 'none'
        }`,
    )
    .join('\n\n');

  const layers = blueprint.layers
    .map(
      (layer) =>
        `- **${layer.name}** (${layer.role}): ${layer.description}${
          layer.frequencyFocus ? ` — ${layer.frequencyFocus}` : ''
        }`,
    )
    .join('\n');

  const chain = blueprint.flStudioChain
    .map(
      (step) =>
        `- **${step.plugin}** — ${step.purpose}; placement: ${step.placement}; start: ${step.startingPoint}`,
    )
    .join('\n');

  return `# ${blueprint.title}

${blueprint.summary}

- BPM: ${blueprint.bpm ?? 'not specified'}
- Key: ${blueprint.key ?? 'not specified'}
- Mood: ${blueprint.mood.primary}${blueprint.mood.secondary.length > 0 ? ` / ${blueprint.mood.secondary.join(', ')}` : ''}
- Model: ${meta.model ?? 'unknown'}
- Generated: ${meta.generatedAt}

## Arrangement

${sections || 'No sections returned.'}

## Layers

${layers || '- None returned'}

## Foley and ambience

${bullet(blueprint.foleyAndAmbience)}

## Automation

${bullet(blueprint.automation)}

## Transitions

${bullet(blueprint.transitions)}

## Production notes

${bullet(blueprint.productionNotes)}

## FL Studio chain (starting points, adjust by ear)

${chain || '- None returned'}

## Assumptions

${bullet(blueprint.assumptions)}

## Uncertainty

${bullet(blueprint.uncertainty)}

Generated by SceneTone from a scene brief. This is a plan, not audio analysis.
`;
}

export function reportToMarkdown(
  report: MixReport,
  meta: { objective: string; metrics: AudioMetrics; model: string | null },
): string {
  const { metrics } = meta;

  return `# Mix report

- Objective: ${meta.objective}
- Model: ${meta.model ?? 'unknown'}
- Duration: ${metrics.durationSeconds}s
- Channels: ${metrics.channels}
- Sample peak: ${metrics.samplePeakDbfs ?? 'unavailable'} dBFS
- RMS: ${metrics.rmsDbfs ?? 'unavailable'} dBFS
- Crest factor: ${metrics.crestFactorDb ?? 'unavailable'} dB
- Band energy: low ${metrics.bandEnergy.low}, mid ${metrics.bandEnergy.mid}, high ${metrics.bandEnergy.high}
- Stereo correlation: ${metrics.stereoCorrelation ?? 'unavailable (mono or silent)'}

## Measured facts

${bullet(report.measuredFacts)}

## Hypotheses

${bullet(report.hypotheses)}

## Recommendations

${bullet(report.recommendations)}

## Limitations

${bullet(report.limitations)}

The model received numeric metrics only. It did not listen to the audio.
`;
}

function download(filename: string, content: string, type: string): void {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}

function safeName(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);
}

export function downloadJson(filename: string, data: unknown): void {
  download(filename, JSON.stringify(data, null, 2), 'application/json');
}

export function downloadMarkdown(filename: string, markdown: string): void {
  download(filename, markdown, 'text/markdown');
}

export function exportBaseName(title: string): string {
  return safeName(title) || 'scenetone';
}
